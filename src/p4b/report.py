"""Markdown report generation.

The report is the artifact a human reads after the pipeline runs: what was found,
which techniques are covered with evidence, and which tests were missed. It is
generated from the database so it always matches what the API would show.
"""

from __future__ import annotations

from datetime import datetime, timezone

from .store.repositories import Repositories
from .validate import build_coverage, score, summarize

SEVERITIES = ("critical", "high", "medium", "low", "info", "unknown")


def build_report(repos: Repositories) -> str:
    summary = repos.summary()
    findings = repos.list_findings(limit=15)
    rules = repos.list_rules(limit=100_000)
    atomics = repos.list_atomics()
    all_findings = repos.list_findings(limit=100_000)
    rows = build_coverage(rules, atomics, all_findings)
    coverage = summarize(rows)
    executions = repos.list_executions()
    validation = score(executions)
    cases = repos.list_cases(limit=20)
    generated = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")

    lines: list[str] = [
        "# P4B report",
        "",
        f"Generated: {generated}",
        "",
        "## Summary",
        "",
        "| Metric | Value |",
        "|---|---|",
        f"| Findings | {summary['total']} |",
        f"| Open | {summary['open']} |",
        f"| Highest risk | {summary['max_risk']} |",
        f"| Techniques seen | {len(summary['techniques'])} |",
        f"| Cases | {len(cases)} |",
        f"| Coverage score | {coverage['score']}% ({coverage['validated']}/{coverage['techniques']}) |",
        f"| Tests detected | {validation['detected']}/{validation['tests']} ({validation['rate']}%) |",
        "",
        "## Findings by severity",
        "",
        "| Severity | Count |",
        "|---|---|",
    ]
    for severity in SEVERITIES:
        lines.append(f"| {severity} | {summary['by_severity'].get(severity, 0)} |")

    lines += ["", "## Findings by source", "", "| Source | Count |", "|---|---|"]
    for source, count in sorted(summary["by_source"].items(), key=lambda item: -item[1]):
        lines.append(f"| {source} | {count} |")

    lines += [
        "",
        "## Top findings by risk",
        "",
        "| Risk | Severity | Source | Title | Asset | ATT&CK |",
        "|---|---|---|---|---|---|",
    ]
    for item in findings:
        title = str(item["title"]).replace("|", "/")[:80]
        asset = str(item["asset"]["key"])[:32]
        techniques = ",".join(item.get("attack") or [])[:32]
        lines.append(
            f"| {item['risk']} | {item['severity']} | {item['source']} | {title} | {asset} | {techniques} |"
        )

    lines += [
        "",
        "## ATT&CK coverage",
        "",
        f"Coverage score is `validated / total`: **{coverage['validated']} of {coverage['techniques']}** techniques "
        f"have a rule, a test, and an observed detection.",
        "",
        "| Technique | Rule | Test | Seen | Status |",
        "|---|---|---|---|---|",
    ]
    for row in rows:
        lines.append(
            f"| {row.technique} | {'yes' if row.has_rule else '-'} | {'yes' if row.has_test else '-'} | "
            f"{'yes' if row.observed else '-'} | {row.status} |"
        )

    lines += [
        "",
        "## Purple-team validation",
        "",
        f"{validation['detected']} of {validation['tests']} executed tests were detected "
        f"({validation['rate']}%).",
        "",
        "| Technique | Test | Host | Detected | Sources |",
        "|---|---|---|---|---|",
    ]
    for item in executions[:25]:
        lines.append(
            f"| {item.get('technique', '')} | {str(item.get('test_name', ''))[:48]} | "
            f"{item.get('host') or '-'} | {'yes' if item.get('detected') else 'no'} | "
            f"{', '.join(item.get('sources') or []) or '-'} |"
        )

    if cases:
        lines += ["", "## Cases", "", "| Case | Priority | Findings | Status |", "|---|---|---|---|"]
        for case in cases:
            lines.append(
                f"| {case['title']} | {case['priority']} | {case['findings']} | {case['status']} |"
            )

    lines += [
        "",
        "---",
        "",
        "Generated by P4B. Coverage counts only techniques with a rule, a test and an observed "
        "detection; everything else is a named gap.",
        "",
    ]
    return "\n".join(lines)
